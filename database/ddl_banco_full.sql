create or replace package body pkg_auth as

  function gerar_hash (p_senha in varchar2, p_salt in varchar2) return varchar2 is
    l_hash varchar2(128);
  begin
    select rawtohex(standard_hash(p_salt || p_senha, 'SHA512'))
      into l_hash
      from dual;
    return l_hash;
  end gerar_hash;

  procedure criar_usuario (p_nome in varchar2, p_email in varchar2, p_senha in varchar2) is
    l_salt varchar2(32) := dbms_random.string('X', 32);
    l_hash varchar2(128);
  begin
    l_hash := gerar_hash(p_senha, l_salt); 

    insert into usuarios (nome, email, senha)
    values (p_nome,
            lower(trim(p_email)),
            l_salt || ':' || l_hash);      
  end criar_usuario;

  function autenticar (p_username in varchar2, p_password in varchar2) return boolean is
    l_senha  usuarios.senha%type;
    l_salt   varchar2(32);
    l_hash   varchar2(128);
  begin
    select senha
      into l_senha
      from usuarios
     where email = lower(trim(p_username));

    -- separa o que está antes e depois do ":"
    l_salt := substr(l_senha, 1, instr(l_senha, ':') - 1);
    l_hash := substr(l_senha, instr(l_senha, ':') + 1);

    return l_hash = gerar_hash(p_password, l_salt);
  exception
    when no_data_found then
      return false;
  end autenticar;

  procedure pos_login is
  begin
    for r in (select id, nome
                from usuarios
               where email = lower(v('APP_USER'))) loop
      apex_util.set_session_state('G_USER_ID',   r.id);
      apex_util.set_session_state('G_USER_NOME', r.nome);
    end loop;
  end pos_login;

end pkg_auth;
/








